"""Build-time generator that embeds SCIBIT JSON configs into a Python module.

Invoked by the nox build session **before** PyInstaller bundles the app.
Reads the developer-facing JSON config files (the "ground truth") from
``packaged_configs/`` and emits ``_bundled_configs.py`` next to this module.

PyInstaller then compiles ``_bundled_configs.py`` into the PYZ archive
**inside** the EXE binary, making the configs truly embedded and
read-only for end users.  Developers keep editing the ``.json`` files;
this module is regenerated on every build.

Usage::

    python -m app.tools.scibit._generate_bundled_configs

The generated module exposes two module-level objects::

    PIPELINE_CONFIGS: dict[str, dict]   # stem -> parsed JSON
    REGEX_PRESETS:    list[dict]         # parsed JSON array

This script is **not** imported at runtime; it only runs at build time.
"""

from __future__ import annotations

import json
import pprint
import subprocess
import sys
from pathlib import Path

#: Directory containing the developer-facing JSON configs (ground truth).
_PACKAGED_CONFIGS_DIR = Path(__file__).parent / "packaged_configs"

#: Sub-directory holding individual pipeline configuration JSON files.
_PIPELINE_CONFIGS_SUBDIR = _PACKAGED_CONFIGS_DIR / "pipeline_configs"

#: The regex presets JSON file.
_PRESETS_FILE = _PACKAGED_CONFIGS_DIR / "scibit_regex_presets.json"

#: Output module written next to this generator.
_OUTPUT_FILE = Path(__file__).parent / "_bundled_configs.py"


def _load_pipeline_configs() -> dict[str, dict]:
    """Read every ``*.json`` under ``pipeline_configs/`` into a dict.

    Returns
    -------
    dict[str, dict]
        Mapping from file stem (config name) to parsed JSON dict.
    """
    configs: dict[str, dict] = {}
    for path in sorted(_PIPELINE_CONFIGS_SUBDIR.glob("*.json")):
        with path.open(encoding="utf-8") as fh:
            configs[path.stem] = json.load(fh)
    return configs


def _load_presets() -> list[dict]:
    """Read the regex presets JSON file into a list of dicts."""
    with _PRESETS_FILE.open(encoding="utf-8") as fh:
        return json.load(fh)


def _format_module(configs: dict[str, dict], presets: list[dict]) -> str:
    """Build the source text of ``_bundled_configs.py``.

    Uses ``pprint.pformat`` so the output is valid Python (``True``/``False``/
    ``None``) rather than JSON (``true``/``false``/``null``), while keeping
    the generated file readable for debugging.
    """
    configs_repr = pprint.pformat(configs, indent=2, width=120, sort_dicts=False)
    presets_repr = pprint.pformat(presets, indent=2, width=120, sort_dicts=False)
    return (
        "# AUTO-GENERATED by app.tools.scibit._generate_bundled_configs.\n"
        "# DO NOT EDIT MANUALLY — edit the .json files in packaged_configs/\n"
        "# and re-run the build to regenerate this file.\n"
        "\n"
        "from __future__ import annotations\n"
        "\n"
        f"PIPELINE_CONFIGS: dict[str, dict] = {configs_repr}\n"
        "\n"
        f"REGEX_PRESETS: list[dict] = {presets_repr}\n"
    )


def generate(output: Path | None = None) -> Path:
    """Generate ``_bundled_configs.py`` from the JSON ground truth.

    After writing, the file is reformatted with ``ruff format`` so the
    generated artifact matches the project's style rules and passes the
    build-time format check.

    Parameters
    ----------
    output : Path | None
        Explicit output path (defaults to ``_OUTPUT_FILE``).

    Returns
    -------
    Path
        Path to the generated module.
    """
    out = output or _OUTPUT_FILE
    configs = _load_pipeline_configs()
    presets = _load_presets()
    out.write_text(_format_module(configs, presets), encoding="utf-8")
    # Reformat with ruff so the generated file passes ``ruff format --check``.
    subprocess.run([sys.executable, "-m", "ruff", "format", str(out)], check=True)
    print(f"Generated {out} ({len(configs)} pipeline configs, {len(presets)} presets)")
    return out


if __name__ == "__main__":
    generate()
